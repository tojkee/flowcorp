// Automation is a tier-gated tree of tools the company owns, not a single linear
// upgrade track. The player owns a *set* of tools; effects stack. The tree is
// organised into four **eras** that tell the company's modernization story —
// Early (manual tooling) → Growing (back-office systems) → AI Era (AI assistants)
// → Advanced (autonomous AI departments / AI executives). Buying tools across the
// eras is the game's main "modernize the company" progression (#7): the player
// stops automating single tasks and starts automating whole departments.
//
// Each tool affects the simulation and changes how the office *looks/feels* so the
// player can directly see automation altering workflow behavior:
//
//   - era               "early" | "growing" | "ai" | "advanced" (UI grouping + ambiance)
//   - speedMultiplier   reduces processing time (global, product — capped)
//   - accuracyBonus     reduces error/rework rates (global, sum — capped)
//   - valueMultiplier   increases payout per completed task (global, product — capped)
//   - moveSpeedMultiplier  speeds task movement between departments (global, product — capped)
//   - capacityBonus     extra parallel work items per targeted department (sum, targeted)
//   - target            department ids the capacity effect focuses on (null = everywhere)
//   - visual            office overlay this tool turns on (workflow-lines / fast-movement /
//                       auto-invoice drive the canvas; ai-terminals drives the AI ambiance)
//
// Per-tool effects are intentionally small because they stack across a deep tree;
// the aggregate is clamped in getAutomationEffects so a fully-modernized company is
// strong but never runaway.

